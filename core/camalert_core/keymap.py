def action_for(player, context, key):
    """Logical action of a key name in a context, or None (= not handled there)."""
    for action, keys in KEYMAP[player][context].items():
        if key in keys:
            return action
    return None


def keys_for(player, context, action):
    return KEYMAP[player][context].get(action, ())


# --- colour keys -> Home Assistant or PTZ ----------------------------------------------------------------------
COLOURS = ("red", "green", "yellow", "blue")
PTZ_TOGGLE_KEYS = ("blue", "yellow", "red", "green", "off")


def colour_action(colour, ptz_toggle="blue", has_ptz=False, enabled=True):
    """'ptz' | colour | None for a colour key while a camera is on screen. The PTZ toggle key only counts as PTZ
    for cameras that have PTZ; for all other cameras every colour key goes to Home Assistant."""
    if colour not in COLOURS:
        return None
    if has_ptz and colour == ptz_toggle:
        return "ptz"
    return colour if enabled else None


def action_menu(has_ptz=False, ptz_key="blue", ha_buttons=True):
    """The entries of the on-screen action menu (#118), in order: ("ptz", None) for camera control on a camera
    with PTZ, then ("button", colour) for every colour key that goes to Home Assistant (the same colours
    colour_action() sends: not the PTZ key of a PTZ camera, none when ha_buttons is off)."""
    out = [("ptz", None)] if has_ptz else []
    for colour in COLOURS:
        if colour_action(colour, ptz_key, has_ptz, ha_buttons) == colour:
            out.append(("button", colour))
    return out


# Signed colour keys (#82): Home Assistant gives the player a secret with the webhook; every key press to the webhook
# carries a time, a one-time nonce and an HMAC-SHA256 over both, so nothing else on the network can fake or replay
# a press (a green key may open a gate). Home Assistant accepts a nonce once and only within BUTTON_MAX_AGE seconds.
BUTTON_MAX_AGE = 60


def button_signature(secret, node, camera, button, ts, nonce):
    """Hex HMAC-SHA256 of one key press; the custom_components/camalert copy must give the same value."""
    msg = "|".join([str(node or ""), str(camera or ""), str(button or ""), str(int(ts)), str(nonce or "")])
    return hmac.new(str(secret).encode("utf-8"), msg.encode("utf-8"), hashlib.sha256).hexdigest()


def button_event(node, camera, button, secret=None, now=None, nonce=None):
    """Payload for camalert/<id>/button (MQTT event entity) and the Home Assistant webhook. With the webhook secret
    (#82) the payload also carries ts, nonce and sig; MQTT payloads are never signed (the broker has its own login)."""
    data = {"event_type": button, "button": button, "camera": camera or "", "receiver": node}
    if secret:
        ts = int(time.time() if now is None else now)
        nonce = nonce or binascii.hexlify(os.urandom(16)).decode("ascii")
        data.update(ts=ts, nonce=nonce, sig=button_signature(secret, node, camera, button, ts, nonce))
    return json.dumps(data, sort_keys=True)
