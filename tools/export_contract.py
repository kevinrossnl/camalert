def _cameras_param(v):
    try:
        return {"ok": api.cameras_param(v)}
    except api.Invalid as e:
        return {"error": str(e)}


def _parse_body(ct, b):
    try:
        return {"ok": api.parse_body(ct, b.encode("utf-8"))}
    except api.Invalid as e:
        return {"error": str(e)}


