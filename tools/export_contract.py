# --- HTTP contract ----------------------------------------------------------------------------------------------------
def http_contract():
    from contract import api_table as T
    from contract.adapters import DEFAULTS
    from fakes import dns
    from fakes.controller import RecordingController
    ctl = RecordingController()
    rows = []
    for r in T.TABLE:
        body = r["body"]
        rows.append({
            "name": r["name"], "path": r["path"], "method": r["method"], "args": r["args"], "ip": r["ip"],
            "header": r["header"], "user_agent": r["user_agent"], "settings": dict(DEFAULTS, **r["settings"]),
            "body": body.decode("utf-8") if body is not None else None,
            "code": r["code"], "json": r["json"],
            "calls": [list(c) for c in r["calls"]] if r["calls"] is not None else None,
            "headers": r["headers"], "check": r["check"].__name__ if r["check"] else None,
            "ctl": r["ctl"], "cameras": r["cameras"],
        })
    return {
        "_": HEADER,
        "defaults": DEFAULTS,
        "controller": {"ptz": sorted(ctl.ptz), "results": ctl.results, "events": ctl.events,
                       "status": ctl.status()},
        "dns": dns.NAMES,
        "status_keys": list(T.STATUS_KEYS),
        "screens": list(T.SCREENS),
        "rate_limit": {"ip": "192.168.1.99", "requests": 35, "limit": api.LIMIT.limit, "window": api.LIMIT.window},
        "rows": rows,
    }


# --- MQTT contract ----------------------------------------------------------------------------------------------------
def _check(fn):
    name = fn.__name__
    if name.startswith("one of "):
        return {"kind": "one_of", "values": name[len("one of "):].split(", ")}
    if name.startswith("json with "):
        return {"kind": "json_keys", "keys": name[len("json with "):].split(", ")}
    return {"kind": "not_empty"}


def mqtt_contract():
    from contract import mqtt_table as T
    cams = [("front_door", "Front door"), ("garden", "Garden")]
    discovery = []
    for topic, payload in mqtt_topics.discovery(T.NODE, "CamAlert test", cams):
        d = json.loads(payload)
        for a, b in T.PLATFORM_FIELDS:
            d[a].pop(b)
        discovery.append({"topic": topic, "payload": d})
    return {
        "_": HEADER,
        "node": T.NODE,
        "name": "CamAlert test",
        "cameras": [{"name": n, "title": t} for n, t in cams],
        "platform_fields": [list(x) for x in T.PLATFORM_FIELDS],
        "published": [{"topic": t, "retain": r, "check": _check(c)} for t, r, c in T.PUBLISHED],
        "subscribed": T.SUBSCRIBED,
        "last_will": {"topic": T.LAST_WILL[0], "payload": T.LAST_WILL[1].decode(), "retain": T.LAST_WILL[2]},
        "client_id": "camalert-{node}",
        "settings": {"mqtt_enabled": True, "mqtt_discovery": True, "mqtt_name": "CamAlert test",
                     "frigate_enabled": True},
        "commands": [{"name": n, "topic": t, "payload": p, "call": list(c)} for n, t, p, c in T.COMMANDS],
        "discovery": discovery,
    }


