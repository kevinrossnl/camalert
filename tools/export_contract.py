def _dump(d):
    return json.dumps(d, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def outputs():
    return {
        os.path.join(TEST_RES, "http.json"): _dump(http_contract()),
        os.path.join(TEST_RES, "mqtt.json"): _dump(mqtt_contract()),
        os.path.join(TEST_RES, "core.json"): _dump(core_reference()),
        os.path.join(MAIN_RES, "core.json"): _dump(runtime()),
    }


def main(argv):
    mode = argv[1] if len(argv) > 1 else "check"
    stale = []
    for path, text in sorted(outputs().items()):
        try:
            with open(path, encoding="utf-8") as f:
                same = f.read() == text
        except IOError:
            same = False
        if not same:
            stale.append(os.path.relpath(path, ROOT))
            if mode == "update":
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    for rel in stale:
        print(("updated " if mode == "update" else "out of date (run tools/export_contract.py update): ") + rel)
    return 1 if stale and mode != "update" else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
