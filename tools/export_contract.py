"""Exports the shared contract and core data to JSON for players that are not written in Python (#64).

The Android TV player (players/androidtv/) re-implements the HTTP API, MQTT and settings in Kotlin. It must
answer exactly like the Python players, so it does not get its own copy of the rules: this tool writes them from
the single sources of truth and the Kotlin tests read the JSON.

    python3 tools/export_contract.py update   write the JSON files
    python3 tools/export_contract.py check    exit 1 if a file is not up to date (tests/test_export_contract.py)

Outputs (generated, never edit by hand):
    players/androidtv/api/src/test/resources/contract/http.json   tests/contract/api_table.py + the fakes it uses
    players/androidtv/api/src/test/resources/contract/mqtt.json   tests/contract/mqtt_table.py + expected discovery
    players/androidtv/api/src/test/resources/contract/core.json   reference answers of core functions (redact,
                                                                  metrics, url checks, key hints, settings) that the
                                                                  Kotlin port must reproduce
    players/androidtv/api/src/main/resources/camalert/core.json   runtime data: API constants, the settings schema
                                                                  of the Android TV player, key map and hints

Plain Python 3.8+, standard library only. Copyright (C) 2026 CamAlert developers, GPL v2.
"""
